#!/usr/bin/env python3
"""gen_game_profile.py: games/<TITLE>/{game.tsv,profile.tsv} -> game_profile.h (the macros windows/src/nxrt/host/dm.h includes).

Same macro names as nxnative's dm/games/game.py; DM_GAME_SLUG and DM_GAME_WINDOW_TITLE are the port's own (window title, data and cache folder names).
usage: gen_game_profile.py [--game <TITLE>] [--out FILE]   (default game: Ocarina of Time; no --out: stdout)"""
import argparse, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_GAME = '0400486024DEC000'


def read_tsv(path):
    g = {}
    for line in path.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.startswith('#'): continue
        k, _, v = line.partition('\t'); g.setdefault(k, []).append(v)
    return g


def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def ull(v): return f'0x{int(v, 0):x}ull'


def render(game):
    d = HERE / 'games' / game
    if not (d / 'game.tsv').is_file(): raise SystemExit(f'gen_game_profile: {d / "game.tsv"} does not exist (games/{game}/README.md says what to fill in)')
    g = read_tsv(d / 'game.tsv'); p = read_tsv(d / 'profile.tsv') if (d / 'profile.tsv').is_file() else {}
    one = lambda t, k, default=None: (t.get(k) or [default])[0]
    title, name = one(g, 'title_id'), one(g, 'name')
    mods = one(g, 'modules', 'main').split()
    builds = [l.split('\t') for l in g.get('build', [])]   # version, display, main=..., subsdk0=..., sdk=...
    macro = {r.split('\t')[0]: r.split('\t')[1] for r in p.get('build_macro', [])}
    disp = ', '.join('{%s, %s}' % (q(next(m[5:] for m in b[2:] if m.startswith('main='))), q(b[1])) for b in builds)
    L = [f"// {name}'s game profile as nxnative's dm/games/game.py would generate it (same macro names, so the ported files read it unchanged).",
         f'// Generated by tools/gen_game_profile.py from games/{game}/game.tsv and profile.tsv; do not edit.',
         '#pragma once', '',
         f'#define DM_GAME_ID {q(title)}', f'#define DM_GAME_NAME {q(name)}', f'#define DM_GAME_PROGRAM_ID 0x{int(one(g, "program_id", title), 16):016X}ull',
         '#define DM_GAME_MODULES {%s}' % ', '.join(q(m) for m in mods), f'#define DM_GAME_NMOD {len(mods)}',
         f'#define DM_GAME_MEM_RESERVE {ull(one(g, "mem_reserve"))}', f'#define DM_GAME_MEM_ALIAS {ull(one(g, "mem_alias"))}', f'#define DM_GAME_MEM_STACK {ull(one(g, "mem_stack"))}',
         f'#define DM_GAME_APP_POOL {ull(one(g, "app_pool"))}', f'#define DM_GAME_MEM_USED {ull(one(g, "mem_used", "0x4000000"))}',
         f'#define DM_GAME_SYS_RESOURCE {ull(one(g, "sys_resource", "0"))}',
         f'#define DM_GAME_ARGS {q(one(g, "args", ""))}', f'#define DM_GAME_ENV {q(one(g, "env", ""))}',
         f'#define DM_GAME_MEM_MAP_LIMIT {int(one(g, "mem_map_limit", "0"), 0)}', f'#define DM_GAME_STDALLOC_CAP {ull(one(g, "stdalloc_cap", "0"))}',
         f'#define DM_GAME_CORE_PREEMPT {int(one(g, "core_preempt", "0"), 0)}', f'#define DM_GAME_ALLOC_BIG_ALIGN {int(one(g, "alloc_big_align", "0"), 0)}']
    for b in builds:
        if b[0] in macro: L.append(f'#define DM_GAME_BUILD_{macro[b[0]]} {q(next(m[5:] for m in b[2:] if m.startswith("main=")))}')
    L += [f'#define DM_GAME_ROMFS_MARKER {q(one(g, "romfs_marker", ""))}', f'#define DM_GAME_DISPLAY_VERSIONS {disp}',
          f'#define DM_GAME_PAD_LAYOUT {int(one(g, "pad_layout", "0"), 0)}',
          f'#define DM_GAME_LOOK_RATE {float(one(g, "look_rate", "110"))!r}f', f'#define DM_GAME_LOOK_DEAD {float(one(g, "look_dead", "0.52"))!r}f',
          f'#define DM_GAME_LOOK_CAM {q(one(g, "look_cam", ""))}',
          f'#define DM_GAME_OPMODE {int(one(g, "op_mode", "1"), 0)}', f'#define DM_GAME_PERF_BOOST {int(one(g, "perf_boost", "0"), 0)}',
          '// The port\'s own: window title and the data/cache folder name (<slug>-native)',
          f'#define DM_GAME_SLUG {q(one(p, "slug", title.lower()))}', f'#define DM_GAME_WINDOW_TITLE {q(one(p, "window_title", name))}',
          f'#define DM_GAME_DEFAULT_VERSION {q(one(p, "default_version", "1.0.0"))}']
    if one(p, 'nvn_api'):   # NVN API version the game's own driver would report (Switch 2 NVN2: 231.x); absent: nxrt's table (55.15)
        ma, mi = one(p, 'nvn_api').split('.')
        L += [f'#define DM_GAME_NVN_API_MAJOR {int(ma)}', f'#define DM_GAME_NVN_API_MINOR {int(mi)}']
    L.append('')
    return '\n'.join(L)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0]); ap.add_argument('--game', default=DEFAULT_GAME); ap.add_argument('--out')
    a = ap.parse_args(); text = render(a.game)
    if a.out:
        o = pathlib.Path(a.out); o.parent.mkdir(parents=True, exist_ok=True)
        if not o.is_file() or o.read_text(encoding='utf-8') != text: o.write_text(text, encoding='utf-8', newline='\n')
    else: sys.stdout.write(text)
