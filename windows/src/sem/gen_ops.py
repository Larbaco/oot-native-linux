"""Usage: py -3 -I gen_ops.py <llvm-nm> <nxw_sem library> <a64_gen.hpp> <out sem_ops.inc>

Lists the decoder ops that have a semantic function (nxw_sem_<Op> defined in the library) as NXW_SEM_OP(<Op>) lines, in
decoder order, for the interpreter's dispatch. Fails when a nxw_sem_ function names no decoder op (a typo in a SEM name)."""
import re
import subprocess
import sys

NON_OPS = {'enter', 'leave', 'leave_mask', 'lookup', 'sysreg_inline'}


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    nm, bc, gen_hpp, out = sys.argv[1:]
    text = subprocess.run([nm, '--defined-only', '--format=just-symbols', bc], check=True, capture_output=True,
                          text=True).stdout
    # Mach-O (the Mac build) prefixes C symbols with an underscore
    names = [n[1:] if n.startswith('_nxw_sem_') else n for n in (line.strip() for line in text.splitlines())]
    defined = {n[len('nxw_sem_'):] for n in names if n.startswith('nxw_sem_')}
    enum = open(gen_hpp, encoding='utf-8').read()
    body = enum[enum.index('enum class Op'):]
    body = body[:body.index('};')]
    ops = re.findall(r'^\s+(\w+),', body, re.M)
    unknown = sorted(defined - set(ops) - NON_OPS)
    if unknown:
        sys.exit('gen_ops: semantic functions that name no decoder op: ' + ', '.join(unknown))
    have = [o for o in ops if o in defined]
    lines = ['// Generated by src/sem/gen_ops.py from the semantics bitcode. Do not edit.']
    lines += [f'NXW_SEM_OP({o})' for o in have]
    new = '\n'.join(lines) + '\n'
    try:
        if open(out, encoding='utf-8').read() == new:
            return
    except OSError:
        pass
    open(out, 'w', encoding='utf-8', newline='\n').write(new)
    print(f'gen_ops: {len(have)} of {len(ops) - 1} ops have semantics')


main()
